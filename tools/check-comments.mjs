import { readFileSync, existsSync } from "node:fs";
import { extname } from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const SLASH_LANGS = new Set([".cs", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java", ".go", ".kt", ".swift", ".razor"]);
const HASH_LANGS = new Set([".py"]);
const SQL_LANGS = new Set([".sql"]);

const IGNORED_PATH = /(^|[\\/])(bin|obj|node_modules|dist|build|coverage|Migrations|TestResults|\.git|\.claude[\\/]skills|wwwroot[\\/]lib)([\\/]|$)|\.(Designer|g|generated|min)\.\w+$|ModelSnapshot\.cs$/;

const LINE_COMMENT = new RegExp("(^|[^:])/{2}");

const ALLOWED_TEXT = /^(WHY:|eslint|prettier-ignore|@ts-|istanbul|c8 |<auto-generated|ReSharper|language=|type:|noqa|pragma|-\*-)/i;

export function isCheckedFile(path) {
  const ext = extname(path).toLowerCase();
  if (IGNORED_PATH.test(path)) return false;
  return SLASH_LANGS.has(ext) || HASH_LANGS.has(ext) || SQL_LANGS.has(ext);
}

function blankStrings(line) {
  return line
    .replace(/"(?:\\.|[^"\\])*"/g, (m) => '"' + " ".repeat(Math.max(0, m.length - 2)) + '"')
    .replace(/'(?:\\.|[^'\\])*'/g, (m) => "'" + " ".repeat(Math.max(0, m.length - 2)) + "'")
    .replace(/`(?:\\.|[^`\\])*`/g, (m) => "`" + " ".repeat(Math.max(0, m.length - 2)) + "`");
}

export function findCommentViolations(text, path, lineNumbers = null) {
  const ext = extname(path).toLowerCase();
  const lines = text.split(/\r?\n/);
  const violations = [];
  let inBlock = false;
  let blockAllowed = false;

  lines.forEach((raw, i) => {
    const lineNo = i + 1;
    const report = (snippet) => {
      if (!lineNumbers || lineNumbers.has(lineNo)) violations.push({ line: lineNo, text: snippet.trim().slice(0, 120) });
    };

    if (i === 0 && raw.startsWith("#!")) return;

    if (SLASH_LANGS.has(ext)) {
      let line = blankStrings(raw);
      if (inBlock) {
        const end = line.indexOf("*/");
        if (!blockAllowed) report(raw);
        if (end === -1) return;
        inBlock = false;
        line = line.slice(end + 2);
      }
      const lineIdx = line.search(LINE_COMMENT);
      const blockIdx = line.indexOf("/*");
      const idx = [lineIdx === -1 ? -1 : line.indexOf("//", lineIdx), blockIdx].filter((n) => n >= 0).sort((a, b) => a - b)[0];
      if (idx === undefined) return;
      const isBlock = idx === blockIdx;
      const body = raw.slice(idx).replace(/^\/\/\/?|^\/\*\*?/, "").replace(/\*\/\s*}?\s*$/, "").trim();
      const allowed = ALLOWED_TEXT.test(body);
      if (isBlock) {
        const rest = line.slice(idx + 2);
        if (!rest.includes("*/")) {
          inBlock = true;
          blockAllowed = allowed;
        }
      }
      if (!allowed) report(raw);
      return;
    }

    if (HASH_LANGS.has(ext) || SQL_LANGS.has(ext)) {
      const marker = HASH_LANGS.has(ext) ? "#" : "--";
      const line = blankStrings(raw);
      const idx = line.indexOf(marker);
      if (idx === -1) return;
      const body = raw.slice(idx + marker.length).trim();
      if (!ALLOWED_TEXT.test(body)) report(raw);
    }
  });

  return violations;
}

function git(args) {
  try {
    return execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 * 1024 * 1024 });
  } catch {
    return "";
  }
}

function addedLinesByFile() {
  const diff = git(["diff", "HEAD", "--unified=0", "--no-color", "--no-ext-diff"]);
  const map = new Map();
  let current = null;
  for (const line of diff.split("\n")) {
    const file = line.match(/^\+\+\+ b\/(.+)$/);
    if (file) {
      current = file[1];
      map.set(current, new Set());
      continue;
    }
    const hunk = line.match(/^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/);
    if (hunk && current) {
      const start = Number(hunk[1]);
      const count = hunk[2] === undefined ? 1 : Number(hunk[2]);
      for (let n = start; n < start + count; n++) map.get(current).add(n);
    }
  }
  return map;
}

export function scanRepo({ changedOnly }) {
  const results = [];
  if (changedOnly) {
    const untracked = git(["ls-files", "--others", "--exclude-standard"]).split("\n").filter(Boolean);
    for (const file of untracked.filter(isCheckedFile)) {
      if (!existsSync(file)) continue;
      for (const v of findCommentViolations(readFileSync(file, "utf8"), file)) results.push({ file, ...v });
    }
    for (const [file, lines] of addedLinesByFile()) {
      if (!isCheckedFile(file) || !existsSync(file) || lines.size === 0) continue;
      for (const v of findCommentViolations(readFileSync(file, "utf8"), file, lines)) results.push({ file, ...v });
    }
  } else {
    const files = git(["ls-files", "--cached", "--others", "--exclude-standard"]).split("\n").filter(Boolean);
    for (const file of files.filter(isCheckedFile)) {
      if (!existsSync(file)) continue;
      for (const v of findCommentViolations(readFileSync(file, "utf8"), file)) results.push({ file, ...v });
    }
  }
  return results;
}

export function formatViolations(violations) {
  return [
    "Comment rule violated. Code must explain itself through names, types and tests.",
    "Remove these comments. Keep one only if it explains a non-obvious reason, rewritten as `// WHY: <reason>` (`# WHY:` in Python, `-- WHY:` in SQL).",
    ...violations.map((v) => `  ${v.file ?? ""}${v.file ? ":" : "line "}${v.line}  ${v.text}`),
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const changedOnly = process.argv.includes("--changed");
  const violations = scanRepo({ changedOnly });
  if (violations.length) {
    console.error(formatViolations(violations));
    process.exit(1);
  }
  console.log("check-comments: ok");
}
